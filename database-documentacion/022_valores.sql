
CREATE TABLE public.valores (
    id_valor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_seccion INTEGER NOT NULL,
    texto_superior VARCHAR(100),
    titulo VARCHAR(150) NOT NULL,
    descripcion TEXT NOT NULL DEFAULT '',
    orden INTEGER NOT NULL DEFAULT 1
);


/* CONSTRAINTS */

ALTER TABLE public.valores
ADD CONSTRAINT valores_titulo_check
CHECK (
    BTRIM(titulo) <> ''
);

ALTER TABLE public.valores
ADD CONSTRAINT valores_orden_check
CHECK (
    orden > 0
);


/* FOREIGN KEYS */

ALTER TABLE public.valores
ADD CONSTRAINT valores_seccion_fk
FOREIGN KEY (id_seccion)
REFERENCES public.secciones_pagina(id_seccion)
ON DELETE RESTRICT;


/* VALIDACIÓN DE SECCIÓN */

CREATE OR REPLACE FUNCTION public.validar_seccion_valores()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM public.secciones_pagina
        WHERE id_seccion = NEW.id_seccion
          AND id_pagina = 2
          AND codigo_seccion = 'valores'
    ) THEN
        RAISE EXCEPTION
        'Los valores deben pertenecer a la sección valores de Quiénes somos';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_seccion_valores
BEFORE INSERT OR UPDATE OF id_seccion
ON public.valores
FOR EACH ROW
EXECUTE FUNCTION public.validar_seccion_valores();


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.valores
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.valores
FROM anon, authenticated;

GRANT SELECT
ON public.valores
TO anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.valores
TO service_role;

GRANT USAGE, SELECT
ON SEQUENCE public.valores_id_valor_seq
TO service_role;


/* POLÍTICA PÚBLICA */

CREATE POLICY "Lectura pública valores"
ON public.valores
FOR SELECT
TO anon, authenticated
USING (TRUE);


/* ÍNDICES */

CREATE INDEX valores_seccion_orden_idx
ON public.valores (id_seccion, orden);


/* INSERT - VALORES INSTITUCIONALES */

INSERT INTO public.valores
(id_seccion, texto_superior, titulo, descripcion, orden)
SELECT
    s.id_seccion,
    v.texto_superior,
    v.titulo,
    v.descripcion,
    v.orden
FROM public.secciones_pagina s
CROSS JOIN (
    VALUES
    (
        'TERRITORIO',
        'Identidad y pertenencia territorial',
        'Reconocemos el territorio como parte esencial de nuestra identidad y promovemos el vínculo de las personas con Quilpué y su historia',
        1
    ),
    (
        'ARCHIVO',
        'Memoria y patrimonio',
        'Rescatamos, cuidamos y difundimos las memorias, historias y expresiones que forman parte del patrimonio local.',
        2
    ),
    (
        'VOCES',
        'Participación e inclusión',
        'Creemos en una cultura construida con las voces, experiencias y miradas diversas de quienes habitan nuestro territorio.',
        3
    ),
    (
        'ENCUENTRO',
        'Colaboración y comunidad',
        'Trabajamos colectivamente, generando espacios de encuentro y colaboración para construir y preservar nuestra historia en comunidad.',
        4
    )
) AS v(texto_superior, titulo, descripcion, orden)
WHERE s.id_pagina = 2
  AND s.codigo_seccion = 'valores';


/* SELECT - COMPROBACIÓN */

SELECT
    id_valor,
    texto_superior,
    titulo,
    descripcion,
    orden
FROM public.valores
ORDER BY orden;


/* COLUMNAS */

ALTER TABLE public.valores
ADD COLUMN id_usuario_modificador INTEGER,
ADD COLUMN fec_actualizacion TIMESTAMPTZ;


/* FOREIGN KEY */

ALTER TABLE public.valores
ADD CONSTRAINT valores_usuario_fk
FOREIGN KEY (id_usuario_modificador)
REFERENCES public.usuarios(id_user)
ON DELETE SET NULL;
