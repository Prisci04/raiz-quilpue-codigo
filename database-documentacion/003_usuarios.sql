/*creacion de tabla usuarios, mismo sql que en supabase */

CREATE EXTENSION IF NOT EXISTS pgcrypto;


CREATE TABLE public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    apellido VARCHAR(120),
    email VARCHAR(254) NOT NULL,
    telefono VARCHAR(30),
    password_hash TEXT NOT NULL,
    tipo_usuario VARCHAR(20)
        NOT NULL
        DEFAULT 'publico',
    estado VARCHAR(20)
        NOT NULL
        DEFAULT 'activo',

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),

    fecha_actualizacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),


    CONSTRAINT usuarios_nombre_check
        CHECK (
            BTRIM(nombre) <> ''
        ),

    CONSTRAINT usuarios_email_check
        CHECK (
            BTRIM(email) <> ''
        ),

    CONSTRAINT usuarios_tipo_usuario_check
        CHECK (
            tipo_usuario IN (
                'publico',
                'interno'
            )
        ),

    CONSTRAINT usuarios_estado_check
        CHECK (
            estado IN (
                'activo',
                'inactivo'
            )
        )
);



CREATE UNIQUE INDEX usuarios_email_unique
ON public.usuarios (
    LOWER(email)
);


/* indice*/

CREATE INDEX idx_usuarios_tipo_estado
ON public.usuarios (
    tipo_usuario,
    estado
);


/* trigger fecha actualizacion*/

CREATE OR REPLACE FUNCTION
public.actualizar_fecha_actualizacion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.fecha_actualizacion = NOW();
    RETURN NEW;
END;
$$;


CREATE TRIGGER trigger_usuarios_fecha_actualizacion
BEFORE UPDATE
ON public.usuarios
FOR EACH ROW
EXECUTE FUNCTION
public.actualizar_fecha_actualizacion();


