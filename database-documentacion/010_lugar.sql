CREATE TABLE public.lugar (
  id_lugar         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_lugar     VARCHAR(150) NOT NULL,
  direccion        VARCHAR(250) NOT NULL,
  google_place_id  VARCHAR(255),
  latitud          NUMERIC(9,6),
  longitud         NUMERIC(10,6),
  id_comuna        INTEGER NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.lugar
ADD CONSTRAINT lugar_nombre_check
CHECK (
  BTRIM(nombre_lugar) <> ''
);

ALTER TABLE public.lugar
ADD CONSTRAINT lugar_direccion_check
CHECK (
  BTRIM(direccion) <> ''
);

ALTER TABLE public.lugar
ADD CONSTRAINT lugar_latitud_check
CHECK (
  latitud IS NULL OR latitud BETWEEN -90 AND 90
);

ALTER TABLE public.lugar
ADD CONSTRAINT lugar_longitud_check
CHECK (
  longitud IS NULL OR longitud BETWEEN -180 AND 180
);

ALTER TABLE public.lugar
ADD CONSTRAINT lugar_comuna_fk
FOREIGN KEY (id_comuna)
REFERENCES public.comuna(id_comuna);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.lugar
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.lugar FROM anon;
REVOKE ALL ON public.lugar FROM authenticated;

GRANT SELECT
ON public.lugar
TO anon;

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.lugar
TO service_role;

GRANT USAGE, SELECT
ON SEQUENCE public.lugar_id_lugar_seq
TO service_role;

CREATE POLICY "Lectura publica lugar"
ON public.lugar
FOR SELECT
TO anon
USING (true);


/* ÍNDICES */

CREATE INDEX lugar_comuna_idx
ON public.lugar (id_comuna);

CREATE UNIQUE INDEX lugar_google_place_unique
ON public.lugar (google_place_id)
WHERE google_place_id IS NOT NULL;


/* SELECTS */

SELECT *
FROM public.lugar
ORDER BY id_lugar