CREATE TABLE public.estado_revision (
  id_estado_revision      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_estado_revision  VARCHAR(30) NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.estado_revision
ADD CONSTRAINT estado_revision_nombre_check
CHECK (
  BTRIM(nombre_estado_revision) <> ''
);

ALTER TABLE public.estado_revision
ADD CONSTRAINT estado_revision_nombre_unique
UNIQUE (nombre_estado_revision);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.estado_revision
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.estado_revision FROM anon;
REVOKE ALL ON public.estado_revision FROM authenticated;

GRANT SELECT
ON public.estado_revision
TO service_role;


/* INSERTS */

INSERT INTO public.estado_revision (nombre_estado_revision)
VALUES
  ('Pendiente'),
  ('Aprobado'),
  ('Rechazado');


/* SELECTS */

SELECT *
FROM public.estado_revision
ORDER BY id_estado_revision;