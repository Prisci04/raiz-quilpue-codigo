CREATE TABLE public.estado_inscripcion (
  id_estado_inscripcion      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_estado_inscripcion  VARCHAR(30) NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.estado_inscripcion
ADD CONSTRAINT estado_inscripcion_nombre_check
CHECK (
  BTRIM(nombre_estado_inscripcion) <> ''
);

ALTER TABLE public.estado_inscripcion
ADD CONSTRAINT estado_inscripcion_nombre_unique
UNIQUE (nombre_estado_inscripcion);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.estado_inscripcion
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.estado_inscripcion FROM anon;
REVOKE ALL ON public.estado_inscripcion FROM authenticated;

GRANT SELECT
ON public.estado_inscripcion
TO service_role;


/* INSERTS */

INSERT INTO public.estado_inscripcion (nombre_estado_inscripcion)
VALUES
  ('Confirmada'),
  ('Lista de espera'),
  ('Cancelada');


/* SELECTS */

SELECT *
FROM public.estado_inscripcion
ORDER BY id_estado_inscripcion;