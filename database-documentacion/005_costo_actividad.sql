CREATE TABLE public.costo_actividad (
  id_costo      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_costo  VARCHAR(30) NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.costo_actividad
ADD CONSTRAINT costo_nombre_check
CHECK (
  BTRIM(nombre_costo) <> ''
);

ALTER TABLE public.costo_actividad
ADD CONSTRAINT costo_nombre_unique
UNIQUE (nombre_costo);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.costo_actividad
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.costo_actividad FROM anon;
REVOKE ALL ON public.costo_actividad FROM authenticated;

GRANT SELECT
ON public.costo_actividad
TO anon;

GRANT SELECT
ON public.costo_actividad
TO service_role;

CREATE POLICY "Lectura publica costo actividad"
ON public.costo_actividad
FOR SELECT
TO anon
USING (true);


/* INSERTS */

INSERT INTO public.costo_actividad (nombre_costo)
VALUES
  ('Gratuita'),
  ('Pagada'),
  ('Aporte voluntario');


/* SELECTS */

SELECT *
FROM public.costo_actividad
ORDER BY id_costo;