/* ============================================================
   1. TABLA
   ============================================================ */

CREATE TABLE public.contenidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    /* Título de la publicación */
    titulo VARCHAR(200) NOT NULL,

    /* Texto corto mostrado en la card */
    descripcion VARCHAR(300) NOT NULL,

    /* Texto mostrado en el popup / vista previa */
    resumen TEXT NOT NULL,

    /*
      Nota completa.

      Se almacena como JSONB para permitir contenido enriquecido
      desde el editor administrativo:

      - párrafos
      - títulos
      - subtítulos
      - negrita
      - cursiva
      - subrayado
      - listas
      - citas
      - enlaces
      - imágenes
      - colores permitidos
    */
    contenido JSONB NOT NULL,

    /*
      Tipo de publicación:
      noticia
      patrimonio
      capsula_historica
    */
    tipo VARCHAR(30) NOT NULL,

    /* Imagen principal / portada */
    imagen_url TEXT,

    /*
      Fecha visible de publicación.
      Puede quedar NULL mientras sea borrador.
    */
    fecha_publicacion TIMESTAMPTZ,

    /*
      Estado de la publicación.
    */
    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'borrador',

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),

    fecha_actualizacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),


    /* ========================================================
       CONSTRAINTS
       ======================================================== */

    CONSTRAINT contenidos_titulo_check
        CHECK (
            BTRIM(titulo) <> ''
        ),

    CONSTRAINT contenidos_descripcion_check
        CHECK (
            BTRIM(descripcion) <> ''
        ),

    CONSTRAINT contenidos_resumen_check
        CHECK (
            BTRIM(resumen) <> ''
        ),

    CONSTRAINT contenidos_tipo_check
        CHECK (
            tipo IN (
                'noticia',
                'patrimonio',
                'capsula_historica'
            )
        ),

    CONSTRAINT contenidos_estado_check
        CHECK (
            estado IN (
                'borrador',
                'publicada'
            )
        ),

    /*
      TipTap guarda el documento como objeto JSON.
    */
    CONSTRAINT contenidos_json_check
        CHECK (
            jsonb_typeof(contenido) = 'object'
        )
);


/* ============================================================
   2. ÍNDICES
   ============================================================ */


/*
  Para consultas públicas:

  WHERE estado = 'publicada'
  ORDER BY fecha_publicacion DESC
*/

CREATE INDEX idx_contenidos_estado_fecha
ON public.contenidos (
    estado,
    fecha_publicacion DESC,
    id DESC
);


/*
  Para filtros como:

  Noticias
  Patrimonio
  Cápsulas históricas
*/

CREATE INDEX idx_contenidos_tipo_estado
ON public.contenidos (
    tipo,
    estado
);


/*
  Útil cuando se filtra por tipo y se ordena por fecha.
*/

CREATE INDEX idx_contenidos_tipo_estado_fecha
ON public.contenidos (
    tipo,
    estado,
    fecha_publicacion DESC
);


/* ============================================================
   3. TRIGGER fecha_actualizacion
   ============================================================ */


/*
  DEFAULT NOW() solamente funciona al crear el registro.

  Este trigger actualiza fecha_actualizacion automáticamente
  cuando el contenido sea modificado.
*/

CREATE OR REPLACE FUNCTION
public.actualizar_fecha_actualizacion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN

    NEW.fecha_actualizacion = NOW();

    RETURN NEW;

END;
$$;


CREATE TRIGGER trigger_contenidos_fecha_actualizacion
BEFORE UPDATE
ON public.contenidos
FOR EACH ROW
EXECUTE FUNCTION
public.actualizar_fecha_actualizacion();


/* ============================================================
   4. RLS
   ============================================================ */

ALTER TABLE public.contenidos
ENABLE ROW LEVEL SECURITY;


/*
  Como desactivamos "Automatically expose new tables",
  debemos otorgar SELECT explícitamente.
*/

GRANT SELECT
ON public.contenidos
TO anon;


/*
  El público SOLO puede consultar publicaciones publicadas.

  Un borrador jamás debe aparecer en el portal público.
*/

CREATE POLICY "Lectura pública de contenidos publicados"
ON public.contenidos
FOR SELECT
TO anon
USING (
    estado = 'publicada'
);


