/*creacion de tabla contenidos, mismo sql que en supabase */

CREATE TABLE public.contenidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    descripcion VARCHAR(300) NOT NULL,

    resumen TEXT NOT NULL,
    contenido JSONB NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    imagen_url TEXT,
    fecha_publicacion TIMESTAMPTZ,
    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'borrador',
    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),

        
    CONSTRAINT contenidos_titulo_check
        CHECK (
            BTRIM(titulo) <> ''
        ),

    CONSTRAINT contenidos_descripcion_check
        CHECK (
            BTRIM(descripcion) <> ''
        ),

    CONSTRAINT contenidos_resumen_check
        CHECK (
            BTRIM(resumen) <> ''
        ),

    CONSTRAINT contenidos_tipo_check
        CHECK (
            tipo IN (
                'noticia',
                'patrimonio',
                'capsula_historica'
            )
        ),

    CONSTRAINT contenidos_estado_check
        CHECK (
            estado IN (
                'borrador',
                'publicada'
            )
        ),

    /*
      TipTap guarda el documento como objeto JSON.
    */
    CONSTRAINT contenidos_json_check
        CHECK (
            jsonb_typeof(contenido) = 'object'
        )
);



/*
  Para consultas públicas:

  WHERE estado = 'publicada'
  ORDER BY fecha_publicacion DESC
*/

CREATE INDEX idx_contenidos_estado_fecha
ON public.contenidos (
    estado,
    fecha_publicacion DESC,
    id DESC
);


/*
  Para filtros como:

  Noticias
  Patrimonio
  Cápsulas históricas
*/

CREATE INDEX idx_contenidos_tipo_estado
ON public.contenidos (
    tipo,
    estado
);



CREATE INDEX idx_contenidos_tipo_estado_fecha
ON public.contenidos (
    tipo,
    estado,
    fecha_publicacion DESC
);


/* trigger fecha actualizacion*/

CREATE OR REPLACE FUNCTION
public.actualizar_fecha_actualizacion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN

    NEW.fecha_actualizacion = NOW();

    RETURN NEW;

END;
$$;


CREATE TRIGGER trigger_contenidos_fecha_actualizacion
BEFORE UPDATE
ON public.contenidos
FOR EACH ROW
EXECUTE FUNCTION
public.actualizar_fecha_actualizacion();




