CREATE TABLE public.region (
  id_region      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_region  VARCHAR(100) NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.region
ADD CONSTRAINT region_nombre_check
CHECK (
  BTRIM(nombre_region) <> ''
);

ALTER TABLE public.region
ADD CONSTRAINT region_nombre_unique
UNIQUE (nombre_region);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.region
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.region FROM anon;
REVOKE ALL ON public.region FROM authenticated;

GRANT SELECT
ON public.region
TO anon;

GRANT SELECT
ON public.region
TO service_role;

CREATE POLICY "Lectura publica region"
ON public.region
FOR SELECT
TO anon
USING (true);


