/*creacion de tabla actividades, mismo sql que en supabase */

CREATE TABLE public.actividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(180) NOT NULL,
    descripcion TEXT NOT NULL,
    /* puede quedar NULL mientras todavía no haya sido confirmada.*/
    fecha DATE,
    /* puede quedar NULL mientras todavía no haya sido confirmada.*/
    hora_inicio TIME,
    hora_fin TIME,
    /* puede quedar NULL si aún está pendiente.*/
    lugar VARCHAR(250),

    /* publico general, personas mayores de 18 años, todas las edades*/
    publico_objetivo VARCHAR(250),

    /* presencial, virtual, hibrida*/
    modalidad VARCHAR(20),

    /* abierta, inscripcion, pendiente*/
    tipo_participacion VARCHAR(20)
        NOT NULL
        DEFAULT 'pendiente',

    /* capacidad máxima, NULL puede significar: no existe límite, aún no está confirmado, los cupos disponibles NO se almacenan aquí. Se calcularán posteriormente usando inscripciones.*/
    cupos INTEGER,

    /* gratuito, pagado, voluntario, pendiente*/
    tipo_valor VARCHAR(20)
        NOT NULL
        DEFAULT 'pendiente',

    /* monto de la actividad cuando corresponda, NULL cuando: es gratuita, todavía está pendiente, no existe un monto fijo*/
    valor_monto INTEGER,

    /* cómo se realiza el pago, ejemplos: transferencia bancaria, pago presencial, información entregada después de la inscripción, la plataforma NO procesa pagos.*/
    forma_pago VARCHAR(250),
    informacion_adicional JSONB,

    imagen_url TEXT,

    /* puede ser borrador, pblicada y cancelado*/
    estado VARCHAR(20)
        NOT NULL
        DEFAULT 'borrador',

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),

    fecha_actualizacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),


    CONSTRAINT actividades_titulo_check
        CHECK (
            BTRIM(titulo) <> ''
        ),

    CONSTRAINT actividades_descripcion_check
        CHECK (
            BTRIM(descripcion) <> ''
        ),

    CONSTRAINT actividades_modalidad_check
        CHECK (
            modalidad IS NULL
            OR modalidad IN (
                'presencial',
                'virtual',
                'hibrida'
            )
        ),

    CONSTRAINT actividades_tipo_participacion_check
        CHECK (
            tipo_participacion IN (
                'abierta',
                'inscripcion',
                'pendiente'
            )
        ),

    CONSTRAINT actividades_cupos_check
        CHECK (
            cupos IS NULL
            OR cupos >= 0
        ),

    CONSTRAINT actividades_tipo_valor_check
        CHECK (
            tipo_valor IN (
                'gratuito',
                'pagado',
                'voluntario',
                'pendiente'
            )
        ),

    CONSTRAINT actividades_valor_monto_check
        CHECK (
            valor_monto IS NULL
            OR valor_monto >= 0
        ),

    /*
      Si existe información adicional,
      debe ser un objeto JSON.
    */
    CONSTRAINT actividades_informacion_adicional_check
        CHECK (
            informacion_adicional IS NULL
            OR jsonb_typeof(informacion_adicional) = 'object'
        ),

    CONSTRAINT actividades_estado_check
        CHECK (
            estado IN (
                'borrador',
                'publicada',
                'cancelada'
            )
        ),

    /*
      Si existen ambas horas,
      la hora de término debe ser posterior.
    */
    CONSTRAINT actividades_horario_check
        CHECK (
            hora_inicio IS NULL
            OR hora_fin IS NULL
            OR hora_fin > hora_inicio
        )
);




/*
  Listado público ordenado por fecha.
*/
CREATE INDEX idx_actividades_estado_fecha
ON public.actividades (
    estado,
    fecha,
    id
);


/*
  Calendario / búsquedas por fecha.
*/
CREATE INDEX idx_actividades_fecha
ON public.actividades (
    fecha
);



  
/*
  trigger fecha actualiuzaciuon. 
*/
CREATE OR REPLACE FUNCTION
public.actualizar_fecha_actualizacion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.fecha_actualizacion = NOW();
    RETURN NEW;
END;
$$;


CREATE TRIGGER trigger_actividades_fecha_actualizacion
BEFORE UPDATE
ON public.actividades
FOR EACH ROW
EXECUTE FUNCTION
public.actualizar_fecha_actualizacion();




