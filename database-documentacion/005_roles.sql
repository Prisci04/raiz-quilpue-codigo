/* ============================================================
   1. TABLA
   ============================================================ */

CREATE TABLE public.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    /*
      Código interno utilizado por backend.

      Ej:
      administrador
      editor
    */
    codigo VARCHAR(50) NOT NULL,

    /* Nombre mostrado en el admin */
    nombre VARCHAR(80) NOT NULL,

    descripcion VARCHAR(250),

    /*
      activo
      inactivo
    */
    estado VARCHAR(20)
        NOT NULL
        DEFAULT 'activo',

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),

    fecha_actualizacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),


    CONSTRAINT roles_codigo_check
        CHECK (
            BTRIM(codigo) <> ''
        ),

    CONSTRAINT roles_nombre_check
        CHECK (
            BTRIM(nombre) <> ''
        ),

    CONSTRAINT roles_estado_check
        CHECK (
            estado IN (
                'activo',
                'inactivo'
            )
        )
);


/* ============================================================
   2. VALORES ÚNICOS
   ============================================================ */

CREATE UNIQUE INDEX roles_codigo_unique
ON public.roles (
    LOWER(codigo)
);


CREATE UNIQUE INDEX roles_nombre_unique
ON public.roles (
    LOWER(nombre)
);


/* ============================================================
   3. TRIGGER fecha_actualizacion
   ============================================================ */

/*
  Esta función ya debería existir porque fue creada
  en usuarios.sql.

  No es necesario volver a crearla.
*/

CREATE TRIGGER trigger_roles_fecha_actualizacion
BEFORE UPDATE
ON public.roles
FOR EACH ROW
EXECUTE FUNCTION
public.actualizar_fecha_actualizacion();


