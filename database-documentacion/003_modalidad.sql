CREATE TABLE public.modalidad(
  id_modalidad      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_modalidad  VARCHAR(60) NOT NULL
);

/*CONTRAINTS*/
ALTER TABLE public.modalidad
ADD CONSTRAINT modalidad_nombre_check
CHECK (
  BTRIM(nombre_modalidad) <> ''
);

ALTER TABLE public.modalidad
ADD CONSTRAINT modalidad_nombre_unique
UNIQUE (nombre_modalidad);

/*SEGURIDAD Y PERMISOS*/
ALTER TABLE public.modalidad
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.modalidad FROM anon;
REVOKE ALL ON public.modalidad FROM authenticated;

GRANT SELECT
ON public.modalidad
TO anon;

GRANT SELECT
ON public.modalidad
TO service_role;

CREATE POLICY "Lectura publica modalidad"
ON public.modalidad
FOR SELECT
TO anon
USING (true);

/*INSERT*/
INSERT INTO public.modalidad(nombre_modalidad)
VALUES('Presencial'),('Virtual'),('Híbrida');

/*SELECT*/
SELECT *
FROM public.modalidad
ORDER BY id_modalidad;