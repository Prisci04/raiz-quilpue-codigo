CREATE TABLE public.estado_publicacion (
  id_estado      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_estado  VARCHAR(30) NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.estado_publicacion
ADD CONSTRAINT estado_publicacion_nombre_check
CHECK (
  BTRIM(nombre_estado) <> ''
);

ALTER TABLE public.estado_publicacion
ADD CONSTRAINT estado_publicacion_nombre_unique
UNIQUE (nombre_estado);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.estado_publicacion
ENABLE ROW LEVEL SECURITY;

