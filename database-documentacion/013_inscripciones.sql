CREATE TABLE public.inscripciones (
  id_inscripcion          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre                  VARCHAR(120) NOT NULL,
  apellido                VARCHAR(120) NOT NULL,
  correo                  VARCHAR(254) NOT NULL,
  telefono                VARCHAR(40),
  fec_inscripcion         TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  id_actividad            INTEGER NOT NULL,
  id_estado_inscripcion   INTEGER NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.inscripciones
ADD CONSTRAINT inscripciones_nombre_check
CHECK (
  BTRIM(nombre) <> ''
);

ALTER TABLE public.inscripciones
ADD CONSTRAINT inscripciones_apellido_check
CHECK (
  BTRIM(apellido) <> ''
);

ALTER TABLE public.inscripciones
ADD CONSTRAINT inscripciones_correo_check
CHECK (
  BTRIM(correo) <> ''
);


/* FOREIGN KEYS */

ALTER TABLE public.inscripciones
ADD CONSTRAINT inscripciones_actividad_fk
FOREIGN KEY (id_actividad)
REFERENCES public.actividades(id_actividad);

ALTER TABLE public.inscripciones
ADD CONSTRAINT inscripciones_estado_fk
FOREIGN KEY (id_estado_inscripcion)
REFERENCES public.estado_inscripcion(id_estado_inscripcion);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.inscripciones
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.inscripciones FROM anon;
REVOKE ALL ON public.inscripciones FROM authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.inscripciones
TO service_role;

GRANT USAGE, SELECT
ON SEQUENCE public.inscripciones_id_inscripcion_seq
TO service_role;


/* ÍNDICES */

CREATE INDEX inscripciones_actividad_idx
ON public.inscripciones (id_actividad);

CREATE INDEX inscripciones_estado_idx
ON public.inscripciones (id_estado_inscripcion);

CREATE INDEX inscripciones_correo_idx
ON public.inscripciones (LOWER(correo));


/* SELECTS */

SELECT *
FROM public.inscripciones
ORDER BY fec_inscripcion DESC;