
/* CREATE TABLE */

CREATE TABLE public.integrantes_directorio (
    id_integrante INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_seccion INTEGER NOT NULL,
    id_cargo INTEGER NOT NULL,
    nombre_integrante VARCHAR(150) NOT NULL,
    descripcion TEXT,
    orden INTEGER NOT NULL DEFAULT 1
);


/* CONSTRAINTS */

ALTER TABLE public.integrantes_directorio
ADD CONSTRAINT integrantes_directorio_nombre_check
CHECK (
    BTRIM(nombre_integrante) <> ''
);

ALTER TABLE public.integrantes_directorio
ADD CONSTRAINT integrantes_directorio_orden_check
CHECK (
    orden > 0
);


/* FOREIGN KEYS */

ALTER TABLE public.integrantes_directorio
ADD CONSTRAINT integrantes_directorio_seccion_fk
FOREIGN KEY (id_seccion)
REFERENCES public.secciones_pagina(id_seccion)
ON DELETE RESTRICT;

ALTER TABLE public.integrantes_directorio
ADD CONSTRAINT integrantes_directorio_cargo_fk
FOREIGN KEY (id_cargo)
REFERENCES public.cargos_organizacion(id_cargo)
ON DELETE RESTRICT;


/* VALIDACIÓN DE SECCIÓN */

CREATE OR REPLACE FUNCTION public.validar_seccion_directorio()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM public.secciones_pagina s
        WHERE s.id_seccion = NEW.id_seccion
          AND s.id_pagina = 2
          AND s.codigo_seccion = 'directorio'
    ) THEN
        RAISE EXCEPTION
        'Los integrantes deben pertenecer a la sección directorio de Quiénes somos';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_seccion_directorio
BEFORE INSERT OR UPDATE OF id_seccion
ON public.integrantes_directorio
FOR EACH ROW
EXECUTE FUNCTION public.validar_seccion_directorio();


