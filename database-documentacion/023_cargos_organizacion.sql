
/* CREATE TABLE */

CREATE TABLE public.cargos_organizacion (
    id_cargo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cargo VARCHAR(100) NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.cargos_organizacion
ADD CONSTRAINT cargos_organizacion_nombre_check
CHECK (
    BTRIM(nombre_cargo) <> ''
);

ALTER TABLE public.cargos_organizacion
ADD CONSTRAINT cargos_organizacion_nombre_unique
UNIQUE (nombre_cargo);


/* FOREIGN KEYS */

-- No tiene claves foráneas.
-- integrantes_directorio utilizará id_cargo.


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.cargos_organizacion
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.cargos_organizacion
FROM anon, authenticated;

GRANT SELECT
ON public.cargos_organizacion
TO anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.cargos_organizacion
TO service_role;

GRANT USAGE, SELECT
ON SEQUENCE public.cargos_organizacion_id_cargo_seq
TO service_role;


/* POLÍTICA PÚBLICA */

CREATE POLICY "Lectura pública cargos organización"
ON public.cargos_organizacion
FOR SELECT
TO anon, authenticated
USING (TRUE);


/* ÍNDICES */

-- PRIMARY KEY y UNIQUE generan sus índices.
-- No se necesitan índices adicionales.


/* INSERT */

INSERT INTO public.cargos_organizacion
(nombre_cargo)
VALUES
    ('Presidente'),
    ('Presidenta'),
    ('Vicepresidente'),
    ('Vicepresidenta'),
    ('Secretario'),
    ('Secretaria'),
    ('Tesorero'),
    ('Tesorera');


/* SELECT */

SELECT
    id_cargo,
    nombre_cargo
FROM public.cargos_organizacion
ORDER BY id_cargo;
