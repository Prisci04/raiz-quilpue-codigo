CREATE TABLE public.tipo_contenido (
  id_tipo_contenido      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_tipo_contenido  VARCHAR(50) NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.tipo_contenido
ADD CONSTRAINT tipo_contenido_nombre_check
CHECK (
  BTRIM(nombre_tipo_contenido) <> ''
);

ALTER TABLE public.tipo_contenido
ADD CONSTRAINT tipo_contenido_nombre_unique
UNIQUE (nombre_tipo_contenido);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.tipo_contenido
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.tipo_contenido FROM anon;
REVOKE ALL ON public.tipo_contenido FROM authenticated;

GRANT SELECT
ON public.tipo_contenido
TO anon;

GRANT SELECT
ON public.tipo_contenido
TO service_role;

CREATE POLICY "Lectura publica tipo contenido"
ON public.tipo_contenido
FOR SELECT
TO anon
USING (true);


/* INSERTS */

INSERT INTO public.tipo_contenido (nombre_tipo_contenido)
VALUES
  ('Noticia'),
  ('Patrimonio'),
  ('Cápsula histórica'),
  ('Cultura'),
  ('Comunidad');


/* SELECTS */

SELECT *
FROM public.tipo_contenido
ORDER BY id_tipo_contenido;