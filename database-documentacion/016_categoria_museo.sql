CREATE TABLE public.categoria_museo (
  id_categoria_museo      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_categoria        VARCHAR(80) NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.categoria_museo
ADD CONSTRAINT categoria_museo_nombre_check
CHECK (
  BTRIM(nombre_categoria) <> ''
);

ALTER TABLE public.categoria_museo
ADD CONSTRAINT categoria_museo_nombre_unique
UNIQUE (nombre_categoria);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.categoria_museo
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.categoria_museo FROM anon;
REVOKE ALL ON public.categoria_museo FROM authenticated;

GRANT SELECT
ON public.categoria_museo
TO anon;

GRANT SELECT
ON public.categoria_museo
TO service_role;

CREATE POLICY "Lectura publica categoria museo"
ON public.categoria_museo
FOR SELECT
TO anon
USING (true);


