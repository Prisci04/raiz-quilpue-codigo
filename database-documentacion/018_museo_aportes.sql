CREATE TABLE public.museo_aportes (
  id_aporte            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_aportante     VARCHAR(160) NOT NULL,
  /* Nullable: aportes antiguos pueden no tener apellido separado.
     Los aportes nuevos lo exigen en la aplicación. */
  apellido_aportante   VARCHAR(160),
  correo_aportante     VARCHAR(254) NOT NULL,
  titulo               VARCHAR(200) NOT NULL,
  descripcion          TEXT,
  fecha_aproximada     VARCHAR(120),
  lugar_referencia     VARCHAR(250),
  /* Opcional: el aporte puede enviarse sin imagen. */
  imagen_url           TEXT,
  fec_creacion         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  fec_revision         TIMESTAMPTZ,

  id_categoria_museo   INTEGER NOT NULL,
  id_estado_revision   INTEGER NOT NULL,
  id_usuario_revisor   INTEGER
);


/* CONSTRAINTS */

ALTER TABLE public.museo_aportes
ADD CONSTRAINT museo_aportes_nombre_check
CHECK (
  BTRIM(nombre_aportante) <> ''
);

ALTER TABLE public.museo_aportes
ADD CONSTRAINT museo_aportes_apellido_check
CHECK (
  apellido_aportante IS NULL
  OR BTRIM(apellido_aportante) <> ''
);

ALTER TABLE public.museo_aportes
ADD CONSTRAINT museo_aportes_correo_check
CHECK (
  BTRIM(correo_aportante) <> ''
);

ALTER TABLE public.museo_aportes
ADD CONSTRAINT museo_aportes_titulo_check
CHECK (
  BTRIM(titulo) <> ''
);

ALTER TABLE public.museo_aportes
ADD CONSTRAINT museo_aportes_imagen_check
CHECK (
  imagen_url IS NULL
  OR BTRIM(imagen_url) <> ''
);


/* FOREIGN KEYS */

ALTER TABLE public.museo_aportes
ADD CONSTRAINT museo_aportes_categoria_fk
FOREIGN KEY (id_categoria_museo)
REFERENCES public.categoria_museo(id_categoria_museo);

ALTER TABLE public.museo_aportes
ADD CONSTRAINT museo_aportes_estado_fk
FOREIGN KEY (id_estado_revision)
REFERENCES public.estado_revision(id_estado_revision);

ALTER TABLE public.museo_aportes
ADD CONSTRAINT museo_aportes_usuario_revisor_fk
FOREIGN KEY (id_usuario_revisor)
REFERENCES public.usuarios(id_user);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.museo_aportes
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.museo_aportes FROM anon;
REVOKE ALL ON public.museo_aportes FROM authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.museo_aportes
TO service_role;

GRANT USAGE, SELECT
ON SEQUENCE public.museo_aportes_id_aporte_seq
TO service_role;


/* POLÍTICA PÚBLICA */

GRANT SELECT
ON public.museo_aportes
TO anon;

CREATE POLICY "Lectura publica aportes aprobados"
ON public.museo_aportes
FOR SELECT
TO anon
USING (
  EXISTS (
    SELECT 1
    FROM public.estado_revision er
    WHERE er.id_estado_revision = museo_aportes.id_estado_revision
      AND er.nombre_estado_revision = 'Aprobado'
  )
);


/* ÍNDICES */

CREATE INDEX museo_aportes_categoria_idx
ON public.museo_aportes (id_categoria_museo);

CREATE INDEX museo_aportes_estado_idx
ON public.museo_aportes (id_estado_revision);

CREATE INDEX museo_aportes_revisor_idx
ON public.museo_aportes (id_usuario_revisor);


/* SELECTS */

SELECT *
FROM public.museo_aportes
ORDER BY fec_creacion DESC;

