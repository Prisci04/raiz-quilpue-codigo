CREATE TABLE public.tipo_participacion (
  id_tipo_participacion      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_tipo_participacion  VARCHAR(50) NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.tipo_participacion
ADD CONSTRAINT tipo_participacion_nombre_check
CHECK (
  BTRIM(nombre_tipo_participacion) <> ''
);

ALTER TABLE public.tipo_participacion
ADD CONSTRAINT tipo_participacion_nombre_unique
UNIQUE (nombre_tipo_participacion);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.tipo_participacion
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.tipo_participacion FROM anon;
REVOKE ALL ON public.tipo_participacion FROM authenticated;

GRANT SELECT
ON public.tipo_participacion
TO anon;

GRANT SELECT
ON public.tipo_participacion
TO service_role;

CREATE POLICY "Lectura publica tipo participacion"
ON public.tipo_participacion
FOR SELECT
TO anon
USING (true);


