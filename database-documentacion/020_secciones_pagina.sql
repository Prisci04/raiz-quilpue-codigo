CREATE TABLE public.secciones_pagina (
    id_seccion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pagina INTEGER NOT NULL,
    codigo_seccion VARCHAR(80) NOT NULL,
    orden INTEGER NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.secciones_pagina
ADD CONSTRAINT secciones_pagina_codigo_check
CHECK (BTRIM(codigo_seccion) <> '');

ALTER TABLE public.secciones_pagina
ADD CONSTRAINT secciones_pagina_orden_check
CHECK (orden > 0);

ALTER TABLE public.secciones_pagina
ADD CONSTRAINT secciones_pagina_codigo_unique
UNIQUE (id_pagina, codigo_seccion);

ALTER TABLE public.secciones_pagina
ADD CONSTRAINT secciones_pagina_orden_unique
UNIQUE (id_pagina, orden);


/* FOREIGN KEYS */

ALTER TABLE public.secciones_pagina
ADD CONSTRAINT secciones_pagina_pagina_fk
FOREIGN KEY (id_pagina)
REFERENCES public.paginas(id_pagina)
ON DELETE RESTRICT;


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.secciones_pagina
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.secciones_pagina
FROM anon, authenticated;

GRANT SELECT
ON public.secciones_pagina
TO anon, authenticated;

GRANT SELECT
ON public.secciones_pagina
TO service_role;


/* POLÍTICA PÚBLICA */

CREATE POLICY "Lectura pública secciones"
ON public.secciones_pagina
FOR SELECT
TO anon, authenticated
USING (TRUE);


/* ÍNDICES */

CREATE INDEX secciones_pagina_pagina_idx
ON public.secciones_pagina (id_pagina);


/* INSERT */

INSERT INTO public.secciones_pagina
(id_pagina, codigo_seccion, orden)
VALUES
    (1, 'portada', 1),
    (1, 'presentacion', 2),
    (2, 'presentacion_mision', 1),
    (2, 'valores', 2),
    (2, 'directorio', 3),
