/* SELECT */

SELECT
    p.nombre_pagina,
    s.id_seccion,
    s.codigo_seccion,
    s.orden
FROM public.secciones_pagina s
INNER JOIN public.paginas p
    ON p.id_pagina = s.id_pagina
ORDER BY
    p.id_pagina,
    s.orden;
