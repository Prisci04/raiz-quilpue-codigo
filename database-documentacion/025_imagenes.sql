
/* CREATE TABLE */

CREATE TABLE public.imagenes (
    id_imagen INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket VARCHAR(100) NOT NULL DEFAULT 'public-media',
    ruta_imagen TEXT NOT NULL,
    descripcion_imagen TEXT,
    fec_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


/* CONSTRAINTS */

ALTER TABLE public.imagenes
ADD CONSTRAINT imagenes_bucket_check
CHECK (
    BTRIM(bucket) <> ''
);

ALTER TABLE public.imagenes
ADD CONSTRAINT imagenes_ruta_check
CHECK (
    BTRIM(ruta_imagen) <> ''
);

ALTER TABLE public.imagenes
ADD CONSTRAINT imagenes_ruta_unique
UNIQUE (bucket, ruta_imagen);



/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.imagenes
ENABLE ROW LEVEL SECURITY;

REVOKE ALL
ON public.imagenes
FROM anon, authenticated;

GRANT SELECT
ON public.imagenes
TO anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.imagenes
TO service_role;

GRANT USAGE, SELECT
ON SEQUENCE public.imagenes_id_imagen_seq
TO service_role;


/* POLÍTICA PÚBLICA */

CREATE POLICY "Lectura publica imagenes"
ON public.imagenes
FOR SELECT
TO anon, authenticated
USING (TRUE);


/* ÍNDICES */



/* INSERT - IMÁGENES EXISTENTES EN STORAGE */

INSERT INTO public.imagenes (
    bucket,
    ruta_imagen
)
SELECT
    o.bucket_id,
    o.name
FROM storage.objects o
WHERE o.bucket_id = 'public-media'
  AND o.name ~* '\.(jpg|jpeg|png|webp|gif|avif)$'
ON CONFLICT (bucket, ruta_imagen)
DO NOTHING;


/* SELECT - COMPROBACIÓN */

SELECT
    id_imagen,
    bucket,
    ruta_imagen,
    descripcion_imagen,
    fec_creacion
FROM public.imagenes
ORDER BY id_imagen;


/* SELECT - TOTAL DE IMÁGENES REGISTRADAS */

SELECT
    bucket,
    COUNT(*) AS total_imagenes
FROM public.imagenes
GROUP BY bucket
ORDER BY bucket;
