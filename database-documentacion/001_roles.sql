CREATE TABLE public.roles (
  id_rol          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_rol      VARCHAR(50) NOT NULL,
  desc_rol        VARCHAR(100) NOT NULL
);

/*CONTRAINTS*/
ALTER TABLE public.roles
add constraint roles_nombre_check
CHECK (
  BTRIM(nombre_rol) <> ''
);

/*SEGURIDAD Y PERMISOS*/
ALTER TABLE public.roles
ENABLE ROW LEVEL security;

REVOKE ALL ON public.roles FROM anon;
REVOKE ALL ON public.roles FROM authenticated;

GRANT select
ON public.roles
TO service_role;

GRANT USAGE, select
ON SEQUENCE public.roles_id_rol_seq
TO service_role;

/*ÍNDICES*/

CREATE UNIQUE INDEX roles_nombre_unique
ON public.roles (
    LOWER(nombre_rol)
);

/* INSERT*/

INSERT INTO public.roles (nombre_rol, desc_rol)
VALUES('Administrador','Acceso completo al portal administrativo.'),
      ('Editor','Usuario encargado de gestionar contenidos y actividades.');

/*SELECTS*/
SELECT *
FROM public.roles
ORDER BY id_rol;
