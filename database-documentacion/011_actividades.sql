/* POLÍTICA PÚBLICA */

CREATE POLICY "Lectura publica actividades"
ON public.actividades
FOR SELECT
TO anon
USING (
  EXISTS (
    SELECT 1
    FROM public.estado_publicacion ep
    WHERE ep.id_estado = actividades.id_estado
      AND ep.nombre_estado = 'Publicada'
  )
);


