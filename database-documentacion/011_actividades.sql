CREATE TABLE public.actividades (
  id_actividad            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo                  VARCHAR(180) NOT NULL,
  descripcion             TEXT,
  fecha                   DATE NOT NULL,
  hora_inicio             TIME,
  hora_fin                TIME,
  cupos_max               INTEGER,
  cupos_espera            INTEGER NOT NULL DEFAULT 0,
  valor_monto             INTEGER,
  informacion_adicional   JSONB,
  imagen_url              TEXT,
  fec_creacion            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  fec_actualizacion       TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  id_modalidad            INTEGER NOT NULL,
  id_tipo_participacion   INTEGER,
  id_publico              INTEGER NOT NULL,
  id_costo                INTEGER,
  id_lugar                INTEGER NOT NULL,
  id_estado               INTEGER NOT NULL,
  id_usuario_creador      INTEGER NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.actividades
ADD CONSTRAINT actividades_titulo_check
CHECK (
  BTRIM(titulo) <> ''
);

ALTER TABLE public.actividades
ADD CONSTRAINT actividades_horas_check
CHECK (
  hora_fin IS NULL
  OR hora_inicio IS NULL
  OR hora_fin > hora_inicio
);

ALTER TABLE public.actividades
ADD CONSTRAINT actividades_cupos_max_check
CHECK (
  cupos_max IS NULL OR cupos_max > 0
);

ALTER TABLE public.actividades
ADD CONSTRAINT actividades_cupos_espera_check
CHECK (
  cupos_espera >= 0
);

ALTER TABLE public.actividades
ADD CONSTRAINT actividades_valor_check
CHECK (
  valor_monto IS NULL OR valor_monto >= 0
);


