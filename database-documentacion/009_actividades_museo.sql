CREATE TABLE public.actividad_inscripciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actividad_id BIGINT NOT NULL REFERENCES public.actividades(id) ON DELETE CASCADE,
    nombre VARCHAR(120) NOT NULL,
    apellido VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    telefono VARCHAR(40) NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT actividad_inscripciones_email_check
        CHECK (POSITION('@' IN email) > 1),
    CONSTRAINT actividad_inscripciones_nombre_check
        CHECK (BTRIM(nombre) <> '' AND BTRIM(apellido) <> '')
);

CREATE INDEX idx_actividad_inscripciones_actividad
    ON public.actividad_inscripciones (actividad_id, fecha_creacion DESC);

ALTER TABLE public.actividad_inscripciones ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.actividad_inscripciones FROM anon, authenticated;
GRANT SELECT, INSERT, DELETE ON public.actividad_inscripciones TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.actividad_inscripciones_id_seq TO service_role;

CREATE TABLE public.museo_piezas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    descripcion TEXT NOT NULL,
    categoria VARCHAR(40) NOT NULL,
    fecha_aproximada VARCHAR(120),
    lugar VARCHAR(250),
    imagen_url TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'borrador',
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT museo_piezas_titulo_check CHECK (BTRIM(titulo) <> ''),
    CONSTRAINT museo_piezas_descripcion_check CHECK (BTRIM(descripcion) <> ''),
    CONSTRAINT museo_piezas_categoria_check CHECK (
        categoria IN (
            'fotografias',
            'documentos',
            'objetos_piezas',
            'memorias_relatos',
            'lugares_memoria',
            'cultura_comunidad'
        )
    ),
    CONSTRAINT museo_piezas_estado_check CHECK (estado IN ('borrador', 'publicada'))
);

CREATE INDEX idx_museo_piezas_estado_categoria
    ON public.museo_piezas (estado, categoria, fecha_creacion DESC);

ALTER TABLE public.museo_piezas ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.museo_piezas FROM anon, authenticated;
GRANT SELECT ON public.museo_piezas TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.museo_piezas TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.museo_piezas_id_seq TO service_role;

CREATE POLICY "Lectura pública de piezas publicadas del museo"
    ON public.museo_piezas FOR SELECT TO anon USING (estado = 'publicada');

CREATE TABLE public.museo_aportes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    categoria VARCHAR(40) NOT NULL,
    titulo VARCHAR(200) NOT NULL,
    descripcion TEXT NOT NULL,
    fecha_aproximada VARCHAR(120),
    lugar VARCHAR(250),
    archivo_nombre VARCHAR(255) NOT NULL,
    informacion_adicional TEXT,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT museo_aportes_categoria_check CHECK (
        categoria IN (
            'fotografias',
            'documentos',
            'objetos_piezas',
            'memorias_relatos',
            'lugares_memoria',
            'cultura_comunidad'
        )
    ),
    CONSTRAINT museo_aportes_email_check CHECK (POSITION('@' IN correo) > 1),
    CONSTRAINT museo_aportes_required_check CHECK (
        BTRIM(nombre) <> '' AND BTRIM(titulo) <> '' AND BTRIM(descripcion) <> ''
    )
);

CREATE INDEX idx_museo_aportes_fecha
    ON public.museo_aportes (fecha_creacion DESC);

ALTER TABLE public.museo_aportes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.museo_aportes FROM anon, authenticated;
GRANT INSERT, SELECT, DELETE ON public.museo_aportes TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.museo_aportes_id_seq TO service_role;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.actividades TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.actividades_id_seq TO service_role;
