CREATE TABLE public.contenidos (
  id_contenido        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo              VARCHAR(200) NOT NULL,
  descripcion         VARCHAR(300),
  resumen             TEXT,
  contenido           JSONB,
  imagen_url          TEXT,
  fec_publicacion     TIMESTAMPTZ,
  fec_creacion        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  fec_actualizacion   TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  id_tipo_contenido   INTEGER NOT NULL,
  id_estado           INTEGER NOT NULL,
  id_usuario_creador  INTEGER NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.contenidos
ADD CONSTRAINT contenidos_titulo_check
CHECK (
  BTRIM(titulo) <> ''
);


/* FOREIGN KEYS */

ALTER TABLE public.contenidos
ADD CONSTRAINT contenidos_tipo_contenido_fk
FOREIGN KEY (id_tipo_contenido)
REFERENCES public.tipo_contenido(id_tipo_contenido);

ALTER TABLE public.contenidos
ADD CONSTRAINT contenidos_estado_fk
FOREIGN KEY (id_estado)
REFERENCES public.estado_publicacion(id_estado);

ALTER TABLE public.contenidos
ADD CONSTRAINT contenidos_usuario_fk
FOREIGN KEY (id_usuario_creador)
REFERENCES public.usuarios(id_user);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.contenidos
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.contenidos FROM anon;
REVOKE ALL ON public.contenidos FROM authenticated;

GRANT SELECT
ON public.contenidos
TO anon;

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.contenidos
TO service_role;

GRANT USAGE, SELECT
ON SEQUENCE public.contenidos_id_contenido_seq
TO service_role;


/* POLÍTICA PÚBLICA */

CREATE POLICY "Lectura publica contenidos"
ON public.contenidos
FOR SELECT
TO anon
USING (
  EXISTS (
    SELECT 1
    FROM public.estado_publicacion ep
    WHERE ep.id_estado = contenidos.id_estado
      AND ep.nombre_estado = 'Publicada'
  )
);


/* ÍNDICES */

CREATE INDEX contenidos_tipo_idx
ON public.contenidos (id_tipo_contenido);

CREATE INDEX contenidos_estado_idx
ON public.contenidos (id_estado);

CREATE INDEX contenidos_usuario_idx
ON public.contenidos (id_usuario_creador);

CREATE INDEX contenidos_publicacion_idx
ON public.contenidos (fec_publicacion);


/* SELECTS */

SELECT *
FROM public.contenidos
ORDER BY fec_creacion DESC;