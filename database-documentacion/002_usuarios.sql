CREATE TABLE public.usuarios (
  id_user       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_user   VARCHAR(100) NOT NULL,
  apellido_user VARCHAR(100) NOT NULL,
  correo_user   VARCHAR(250) NOT NULL,
  telefono      VARCHAR(50),
  password      VARCHAR(255) NOT NULL,
  fec_creacion  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  id_rol        INTEGER NOT NULL
);

/* CONSTRAINTS */

ALTER TABLE public.usuarios
ADD CONSTRAINT usuarios_nombre_check
CHECK (
  BTRIM(nombre_user) <> ''
);

ALTER TABLE public.usuarios
ADD CONSTRAINT usuarios_correo_check
CHECK (
  BTRIM(correo_user) <> ''
);

ALTER TABLE public.usuarios
ADD CONSTRAINT usuarios_rol_fk
FOREIGN KEY (id_rol)
REFERENCES public.roles(id_rol);

/*SEGURIDAD Y PERMISOS*/
ALTER TABLE public.usuarios
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.usuarios FROM anon;
REVOKE ALL ON public.usuarios FROM authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.usuarios
TO service_role;

GRANT USAGE, SELECT
ON SEQUENCE public.usuarios_id_user_seq
TO service_role;

/*ÍNDICES*/
CREATE UNIQUE INDEX usuarios_correo_unique
ON public.usuarios (
  LOWER(correo_user)
);


