/*creacion de tabla sesiones, mismo sql que en supabase */

CREATE TABLE public.sesiones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    token_hash TEXT NOT NULL,
    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),
    ultima_actividad TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),
    fecha_expiracion TIMESTAMPTZ NOT NULL,



/*RELACIONES*/
    CONSTRAINT sesiones_usuario_fk
        FOREIGN KEY (
            usuario_id
        )
        REFERENCES public.usuarios(id)
        ON DELETE CASCADE,


    
    /*
      La expiración siempre debe ocurrir
      después de la creación de la sesión.
    */
    CONSTRAINT sesiones_expiracion_check
        CHECK (
            fecha_expiracion > fecha_creacion
        ),

    /*
      Evita hashes vacíos.
    */
    CONSTRAINT sesiones_token_hash_check
        CHECK (
            BTRIM(token_hash) <> ''
        )
);



/*
  Dos sesiones nunca deberían compartir
  el mismo token_hash.
*/

CREATE UNIQUE INDEX sesiones_token_hash_unique
ON public.sesiones (
    token_hash
);


/*
  Buscar todas las sesiones de un usuario.
*/
CREATE INDEX idx_sesiones_usuario_id
ON public.sesiones (
    usuario_id
);


/*
  Útil para eliminar sesiones expiradas.
*/
CREATE INDEX idx_sesiones_fecha_expiracion
ON public.sesiones (
    fecha_expiracion
);


/*
  Útil para validar inactividad.
*/
CREATE INDEX idx_sesiones_ultima_actividad
ON public.sesiones (
    ultima_actividad
);



ALTER TABLE public.sesiones
ENABLE ROW LEVEL SECURITY;




/*
  Sesiones es una tabla completamente privada.

  El navegador nunca debe leer ni modificar
  esta tabla directamente.
*/

REVOKE ALL
ON public.sesiones
FROM anon;

REVOKE ALL
ON public.sesiones
FROM authenticated;


/*
  Permite al service_role utilizar la secuencia
  generada automáticamente para sesiones.id.
*/
GRANT SELECT, INSERT, UPDATE, DELETE
ON public.sesiones
TO service_role;


SELECT
    id,
    usuario_id,
    fecha_creacion,
    ultima_actividad,
    fecha_expiracion
FROM public.sesiones
ORDER BY id;


SELECT
    schemaname,
    tablename,
    policyname,
    roles,
    cmd
FROM pg_policies
WHERE
    schemaname = 'public'
    AND tablename = 'sesiones';