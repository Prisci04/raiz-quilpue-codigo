/* ============================================================
   1. TABLA
   ============================================================ */

CREATE TABLE public.sesiones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    /*
      Usuario dueño de la sesión.
    */
    usuario_id BIGINT NOT NULL,

    /*
      Hash del token de sesión.

      IMPORTANTE:
      Nunca guardar el token original en la BD.

      El navegador recibe el token original mediante
      una cookie HttpOnly.

      La BD solamente almacena su hash.
    */
    token_hash TEXT NOT NULL,

    /*
      Momento en que se inició la sesión.
    */
    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),

    /*
      Última vez que el usuario tuvo actividad.

      Permitirá cerrar la sesión por inactividad.
    */
    ultima_actividad TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),

    /*
      Fecha máxima hasta la que la sesión puede existir.

      El backend definirá esta fecha al iniciar sesión.

      Ejemplo:
      login + 8 horas.
    */
    fecha_expiracion TIMESTAMPTZ NOT NULL,


    /* ========================================================
       RELACIONES
       ======================================================== */

    CONSTRAINT sesiones_usuario_fk
        FOREIGN KEY (
            usuario_id
        )
        REFERENCES public.usuarios(id)
        ON DELETE CASCADE,


    /* ========================================================
       CONSTRAINTS
       ======================================================== */

    /*
      La expiración siempre debe ocurrir
      después de la creación de la sesión.
    */
    CONSTRAINT sesiones_expiracion_check
        CHECK (
            fecha_expiracion > fecha_creacion
        ),

    /*
      Evita hashes vacíos.
    */
    CONSTRAINT sesiones_token_hash_check
        CHECK (
            BTRIM(token_hash) <> ''
        )
);


/* ============================================================
   2. TOKEN ÚNICO
   ============================================================ */

/*
  Dos sesiones nunca deberían compartir
  el mismo token_hash.
*/

CREATE UNIQUE INDEX sesiones_token_hash_unique
ON public.sesiones (
    token_hash
);


/* ============================================================
   3. ÍNDICES
   ============================================================ */

/*
  Buscar todas las sesiones de un usuario.
*/
CREATE INDEX idx_sesiones_usuario_id
ON public.sesiones (
    usuario_id
);


/*
  Útil para eliminar sesiones expiradas.
*/
CREATE INDEX idx_sesiones_fecha_expiracion
ON public.sesiones (
    fecha_expiracion
);


/*
  Útil para validar inactividad.
*/
CREATE INDEX idx_sesiones_ultima_actividad
ON public.sesiones (
    ultima_actividad
);


/* ============================================================
   4. ROW LEVEL SECURITY
   ============================================================ */

ALTER TABLE public.sesiones
ENABLE ROW LEVEL SECURITY;


/* ============================================================
   5. PERMISOS
   ============================================================ */

/*
  Sesiones es una tabla completamente privada.

  El navegador nunca debe leer ni modificar
  esta tabla directamente.
*/

REVOKE ALL
ON public.sesiones
FROM anon;

REVOKE ALL
ON public.sesiones
FROM authenticated;


/*
  Permite al service_role utilizar la secuencia
  generada automáticamente para sesiones.id.
*/
GRANT SELECT, INSERT, UPDATE, DELETE
ON public.sesiones
TO service_role;

/*
  NO se crean policies públicas.

  Todo acceso será:

  navegador
      ↓
  cookie HttpOnly
      ↓
  API Next.js
      ↓
  backend valida token
      ↓
  Supabase server-only
      ↓
  sesiones
*/


/* ============================================================
   6. VERIFICACIÓN
   ============================================================ */

SELECT
    id,
    usuario_id,
    fecha_creacion,
    ultima_actividad,
    fecha_expiracion
FROM public.sesiones
ORDER BY id;


/* ============================================================
   7. VERIFICAR RLS / POLICIES
   ============================================================ */

SELECT
    schemaname,
    tablename,
    policyname,
    roles,
    cmd
FROM pg_policies
WHERE
    schemaname = 'public'
    AND tablename = 'sesiones';