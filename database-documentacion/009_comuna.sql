CREATE TABLE public.comuna (
  id_comuna      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_comuna  VARCHAR(100) NOT NULL,
  id_region      INTEGER NOT NULL
);


/* CONSTRAINTS */

ALTER TABLE public.comuna
ADD CONSTRAINT comuna_nombre_check
CHECK (
  BTRIM(nombre_comuna) <> ''
);

ALTER TABLE public.comuna
ADD CONSTRAINT comuna_region_fk
FOREIGN KEY (id_region)
REFERENCES public.region(id_region);


/* SEGURIDAD Y PERMISOS */

ALTER TABLE public.comuna
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.comuna FROM anon;
REVOKE ALL ON public.comuna FROM authenticated;

GRANT SELECT
ON public.comuna
TO anon;

GRANT SELECT
ON public.comuna
TO service_role;

CREATE POLICY "Lectura publica comuna"
ON public.comuna
FOR SELECT
TO anon
USING (true);


/* ÍNDICES */

CREATE UNIQUE INDEX comuna_nombre_region_unique
ON public.comuna (
  LOWER(nombre_comuna),
  id_region
);


